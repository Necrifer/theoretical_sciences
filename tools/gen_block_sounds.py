"""
1.10.1: which sound each of the mod's blocks makes (breaking, placing, walking on it), from what it looks like.

* Anything made of rock sounds like vanilla stone (or the vanilla rock it resembles: basalt, tuff, deepslate, gravel).
* Metal blocks, machines and machine parts keep the mod's own machine sound.
* Crystals ring like amethyst, glass and ice sound like glass, lamps like glass, wood like wood, gas and foam like wool.
* Everything else keeps what it had.

Writes registry/QHBlockSounds.java (a lookup by block id), used by QHBlocks.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'main', 'java', 'com', 'theoreticalsciences', 'registry', 'QHBlockSounds.java')

ROCK_BY_ID = {
    'basalt_column': 'BASALT', 'rim_slag': 'BASALT', 'impact_breccia': 'TUFF', 'frontier_regolith': 'GRAVEL', 'antisoil': 'GRAVEL',
    'core_iron': 'STONE', 'pulsar_crust': 'METAL', 'nebular_ice': 'GLASS', 'void_glass': 'GLASS', 'magnetite_block': 'STONE',
    'arbor_planks': 'CHERRY_WOOD', 'station_hull': None, 'cosmic_neutronium_block': None, 'void_tiles': 'DEEPSLATE_TILES',
    'cherenkov_pillar': 'STONE', 'polished_cherenkov_quartz': 'STONE', 'polished_dilithium': 'AMETHYST', 'transcendent_stone': 'STONE',
    'fractal_lattice_block': 'AMETHYST', 'leaded_glass': 'GLASS', 'lithography_glass': 'GLASS', 'hex_glass': 'GLASS',
    'golden_ratio_glass': 'GLASS', 'cloaking_glass': 'GLASS', 'bulk_crystal': 'AMETHYST', 'koch_crystal': 'AMETHYST', 'aleph_glass': 'AMETHYST',
}
STONE_ARTS = {'bulkstone', 'polished', 'axiomstone'}
STONE_STARS = {'ordinal_stone', 'infall_rock', 'antistone'}
STONE_BRICKS = {'cherenkov_bricks', 'spacetime_bricks', 'void_bricks', 'hilbert_brick', 'antistone_bricks', 'magnetite_bricks'}
ORE_BASE = {'stone': 'STONE', 'deepslate': 'DEEPSLATE', 'netherrack': 'NETHER_ORE', 'end_stone': 'STONE', 'basalt_column': 'BASALT',
            'rim_slag': 'BASALT', 'nebular_ice': 'GLASS', 'void_glass': 'GLASS', 'pulsar_crust': 'METAL', 'impact_breccia': 'TUFF',
            'frontier_regolith': 'GRAVEL'}


def sound(b, by_id):
    i, k, art = b['id'], b['kind'], b.get('art')
    if k in ('deco_stairs', 'deco_slab', 'deco_wall'):
        base = b.get('base') or next((i[:-len(s)] for s in ('_stairs', '_slab', '_wall') if i.endswith(s)), None)
        return sound(by_id[base], by_id) if base in by_id else None
    if i in ROCK_BY_ID:
        return ROCK_BY_ID[i]
    if k == 'ore':
        base = b.get('base')
        if base == 'foam_substrate':
            return None
        return ORE_BASE.get(base, 'STONE')
    if k == 'unbreakable' or k.startswith('proof'):
        return None
    if k == 'simple':
        if art in STONE_ARTS or i in STONE_STARS:
            return 'STONE'
        if art == 'crystalblock':
            return 'AMETHYST'
        return None
    if k == 'deco':
        if art == 'lamp':
            return 'GLASS'
        if art == 'bricks' and i in STONE_BRICKS:
            return 'STONE'
        return None
    if k == 'deco_pillar' and i in STONE_BRICKS:
        return 'STONE'
    if k == 'cloud':
        return 'WOOL'
    return None


def main():
    C = json.load(open(os.path.join(HERE, 'content.json')))
    by_id = {b['id']: b for b in C['blocks']}
    groups = {}
    for b in C['blocks']:
        s = sound(b, by_id)
        if s:
            groups.setdefault(s, []).append(b['id'])
    cases = []
    for s, ids in sorted(groups.items()):
        lines, cur = [], []
        for i in sorted(ids):
            cur.append(f'"{i}"')
            if len(cur) == 6:
                lines.append(', '.join(cur))
                cur = []
        if cur:
            lines.append(', '.join(cur))
        cases.append('            case ' + ',\n                 '.join(lines) + f' -> SoundType.{s};')
    java = '''package com.theoreticalsciences.registry;

import net.minecraft.world.level.block.SoundType;

/** Generated by tools/gen_block_sounds.py (1.10.1): each block sounds like what it looks like. Null = keep its kind's sound. */
public final class QHBlockSounds {
    public static SoundType of(String id) {
        return switch (id) {
%s
            default -> null;
        };
    }

    private QHBlockSounds() {}
}
''' % '\n'.join(cases)
    open(OUT, 'w').write(java)
    print('block sounds:', sum(len(v) for v in groups.values()), 'blocks in', len(groups), 'sounds')


if __name__ == '__main__':
    main()
